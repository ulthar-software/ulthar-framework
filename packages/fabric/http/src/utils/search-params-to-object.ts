export function searchParamsToObject(searchParams: URLSearchParams): object {
  const obj: Record<string, string | string[]> = {};
  searchParams.forEach((value, key) => {
    if (obj[key]) {
      if (Array.isArray(obj[key])) {
        obj[key].push(value);
      } else {
        obj[key] = [obj[key], value];
      }
    } else {
      obj[key] = value;
    }
  });
  return obj;
}
